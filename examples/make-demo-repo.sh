package upload

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/http"
	"os"
	"strings"
)

// Disk saves uploads as files under Root.
type Disk struct {
	Root string
}

// Save writes the request body to a new file and returns its id.
func (d Disk) Save(r *http.Request) (string, error) {
	id, err := newID()
	if err != nil {
		return "", err
	}
	path := d.Root
	if !strings.HasSuffix(path, "/") {
		path += "/"
	}
	path += id[:2] + "/"
	path += id
	f, err := os.Create(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	_, err = f.ReadFrom(r.Body)
	return id, err
}

func newID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("upload: cannot make an id: %w", err)
	}
	return hex.EncodeToString(b), nil
}
